export interface MaterialIconProps {
  name: string;
  filled?: boolean;
  className?: string;
  title?: string;
  style?: CSSProperties;
}

/**
 * Renders instant, bundle-compiled inline SVG Material Design icons via `react-icons/md`.
 * Supports both Outlined (default) and Filled variants so no external icon webfont is needed.
 */
export function MaterialIcon({
  name,
  filled = false,
  className = "",
  title,
  style,
}: MaterialIconProps) {
  const entry = ICON_MAP[name.trim()];
  const isFilled =
    filled ||
    Boolean(
      style?.fontVariationSettings &&
        String(style.fontVariationSettings).includes("1")
    );

  const IconComponent = entry
    ? isFilled
      ? entry.filled
      : entry.outlined
    : MdCheckCircle;

  return (
    <IconComponent
      aria-hidden={title ? undefined : true}
      title={title}
      className={`inline-block shrink-0 select-none ${className}`}
    />
  );
}
